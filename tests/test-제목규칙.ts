/**
 * **제목이 「앞머리 세부 키워드 조합 + 후킹 문구」 꼴인지 재는 자를 시험한다.** (3차)
 *
 *     npx tsx tests/test-제목규칙.ts
 *
 * AI 를 부르지 않으므로 인터넷도 키도 필요 없고 1초 안에 끝난다.
 */
import { 제목꼴인가, 제목재보기, 제목고르기, buildTitleRuleBlock, 목표최소, 목표최대 }
  from "../src/claude/제목규칙.js";

let 틀린것 = 0;
function 참(말: string, 값: boolean) {
  if (값) console.log(`   ✅ ${말}`);
  else { console.log(`   ❌ ${말}`); 틀린것 += 1; }
}

console.log("\n① 키워드 조합 + 후킹 문구, 32~40자 제목은 통과한다");
for (const [제목, 키워드] of [
  ["노원구 소형 아파트 대출 조건 2026 바뀐 한도 3가지 총정리", "노원구 소형 아파트 대출 조건"],
  ["초등 스크래치 게임 만들기 주말 1시간이면 첫 작품 완성", "초등 스크래치 게임 만들기"],
  ["강남 원룸 전세 사기 예방 계약 전 이것 5가지만 확인하세요", "강남 원룸 전세 사기 예방"],
  ["캠핑 화로대 추천 순위 3년 써 보고 고른 가성비 TOP5", "캠핑 화로대 추천 순위"],
  ["2026 청년 전세자금대출 조건 몰라서 손해 보셨나요?", "2026 청년 전세자금대출 조건"],
  ["부산 초등 코딩학원 비용 동네별로 비교해 보니 30% 차이", "부산 초등 코딩학원 비용"],
] as const) {
  const 판 = 제목재보기(제목, 키워드);
  참(`"${제목}" (${[...제목].length}자)${판.괜찮나 ? "" : " → " + 판.왜}`, 판.괜찮나);
}

console.log("\n② 걸러낼 것");
for (const [제목, 키워드, 까닭] of [
  ["노원구 소형 아파트 대출 조건", "", "키워드만 있고 후킹이 없어 너무 짧다"],
  ["초등 스크래치 게임 만들기", "", "2차 꼴 — 이제는 짧다"],
  ["노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다", "", "기사 문장"],
  ["스크래치 4.0 AI 도입 선언이 게임 개발 꿈나무들을 흔든 내막", "", "헤드라인 꼬리말"],
  ["요즘 전세 대출 조건 2026 달라진 한도와 금리 한눈에 정리", "", "넓은 수식어로 시작"],
  ["노원구 아파트 대출 조건 알아보니 생각보다 까다로웠습니다", "", "서술형 끝맺음"],
  ["노원구 아파트 대출 조건 정말 이게 맞나요?? 다들 어떻게 하셨나요!", "", "물음표·느낌표 여럿"],
  ["2026 바뀐 대출 한도 3가지 노원구 소형 아파트 대출 조건", "노원구 소형 아파트 대출 조건", "키워드가 앞머리가 아니다"],
  ["“노원구 소형 아파트 대출 조건” 2026 바뀐 한도 3가지 총정리", "", "따옴표"],
] as const) {
  const 판 = 제목재보기(제목, 키워드);
  참(`${까닭}: "${제목.slice(0, 26)}…" → ${판.왜}`, !판.괜찮나);
}

console.log("\n③ 본 제목이 짧으면(옛 꼴) 후킹이 붙은 후보로 바꿔 끼운다");
{
  const 난것 = 제목고르기(
    "노원구 소형 아파트 대출 조건",
    ["노원구 소형 아파트 대출 조건 모르고 계약하면 손해 보는 3가지",
     "노원 아파트 대출 신청 방법 은행 가기 전 5분 체크리스트"],
    "노원구 소형 아파트 대출 조건",
  );
  참("바꿨다고 알린다", 난것.바꿨나);
  참(`새 제목이 규칙에 맞다 ("${난것.title}")`, 제목꼴인가(난것.title));
  참("밀려난 본 제목을 버리지 않는다", 난것.title_variants.includes("노원구 소형 아파트 대출 조건"));
}

console.log("\n④ 본 제목이 이미 규칙에 맞으면 손대지 않는다");
{
  const 본것 = "초등 스크래치 게임 만들기 주말 1시간이면 첫 작품 완성";
  const 난것 = 제목고르기(본것, ["스크래치 주니어 실사용 후기 6개월 써 보고 알게 된 장단점"], "초등 스크래치 게임 만들기");
  참("그대로 둔다", !난것.바꿨나 && 난것.title === 본것);
}

console.log("\n⑤ 쓸 만한 후보가 없으면 아무것도 바꾸지 않는다 (나쁜 제목 < 없는 제목)");
{
  const 본것 = "대출을 조였더니 노원 아파트값이 도리어 뛰었습니다";
  const 난것 = 제목고르기(본것, ["이번 주 부동산 시장은 어떻게 흘러갔을까요"]);
  참("본 제목을 지킨다", !난것.바꿨나 && 난것.title === 본것);
  참("까닭을 남긴다", 난것.왜.includes("후보 제목이 없어"));
}

console.log("\n⑥ 프롬프트가 새 규칙을 시킨다");
{
  const 글 = buildTitleRuleBlock();
  참(`길이 ${목표최소}~${목표최대}자를 시킨다`, 글.includes(`${목표최소}~${목표최대}자`));
  참("앞머리 키워드 + 후킹 문구 두 부분", 글.includes("[앞머리 세부 키워드 조합] + [후킹 문구]"));
  참("8가지 멈추는 이유를 준다", 글.includes("손실회피") && 글.includes("호기심"));
  참("수익 보장 같은 과장을 막는다", 글.includes("수익 보장"));
}

console.log(틀린것 === 0 ? "\n전부 통과했습니다.\n" : `\n${틀린것}건 틀렸습니다.\n`);
process.exit(틀린것 === 0 ? 0 : 1);
