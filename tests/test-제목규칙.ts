/**
 * **제목이 「세부 키워드 조합」 꼴인지 재는 자를 시험한다.**
 *
 *     npx tsx tests/test-제목규칙.ts
 *
 * AI 를 부르지 않으므로 인터넷도 키도 필요 없고 1초 안에 끝난다.
 */
import { 제목꼴인가, 제목재보기, 제목고르기 } from "../src/claude/제목규칙.js";

let 틀린것 = 0;
function 참(말: string, 값: boolean) {
  if (값) console.log(`   ✅ ${말}`);
  else { console.log(`   ❌ ${말}`); 틀린것 += 1; }
}

console.log("\n① 지시하신 「수정 제목」은 통과해야 한다");
for (const 것 of [
  "노원구 소형 아파트 대출 조건",
  "초등 스크래치 게임 만들기",
  "강남 원룸 전세 사기 예방",
  "캠핑 화로대 추천 순위",
  // 실제 Claude 가 새 프롬프트로 내놓은 제목들. 5~6낱말이어도 키워드 조합이면 통과해야 한다.
  "수도권 소형 아파트 전세 계약 조건",
  "초등 파이썬 코딩 시작 방법",
  "서울 아파트 전세 보증금 인상 한도",
]) 참(`"${것}"`, 제목꼴인가(것));

console.log("\n② 지시하신 「원 제목」은 걸러내야 한다");
for (const 것 of [
  "노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다",
  "스크래치 4.0의 AI 도입 선언이 전 세계 게임 개발 꿈나무들을 충격에 빠뜨린 내막",
  "요즘 부동산 시장이 심상치 않네요",
  "대출 규제, 정말 효과가 있을까요",
  "아파트",
]) 참(`"${것.slice(0, 28)}…" → ${제목재보기(것).왜}`, !제목꼴인가(것));

console.log("\n③ 본 제목이 문장이면 후보 제목으로 바꿔 끼운다");
{
  const 난것 = 제목고르기(
    "대출을 조였더니 노원 아파트값이 도리어 뛰었습니다",
    ["노원구 소형 아파트 대출 조건", "노원 아파트 실거래가 정리"],
  );
  참("바꿨다고 알린다", 난것.바꿨나);
  참(`새 제목이 규칙에 맞다 ("${난것.title}")`, 제목꼴인가(난것.title));
  참("밀려난 본 제목을 버리지 않는다", 난것.title_variants.some((t) => t.includes("도리어")));
  참("후보가 중복되지 않는다", new Set(난것.title_variants).size === 난것.title_variants.length);
}

console.log("\n④ 본 제목이 이미 규칙에 맞으면 손대지 않는다");
{
  const 난것 = 제목고르기("초등 스크래치 게임 만들기", ["스크래치 주니어 실사용 후기"]);
  참("그대로 둔다", !난것.바꿨나 && 난것.title === "초등 스크래치 게임 만들기");
  참("후보도 그대로다", 난것.title_variants.length === 1);
}

console.log("\n⑤ 쓸 만한 후보가 없으면 아무것도 바꾸지 않는다 (나쁜 제목 < 없는 제목)");
{
  const 본것 = "대출을 조였더니 노원 아파트값이 도리어 뛰었습니다";
  const 난것 = 제목고르기(본것, ["이번 주 부동산 시장은 어떻게 흘러갔을까요"]);
  참("본 제목을 지킨다", !난것.바꿨나 && 난것.title === 본것);
  참("까닭을 남긴다", 난것.왜.includes("후보 제목이 없어"));
}

console.log(틀린것 === 0 ? "\n전부 통과했습니다.\n" : `\n${틀린것}건 틀렸습니다.\n`);
process.exit(틀린것 === 0 ? 0 : 1);
