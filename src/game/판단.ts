/**
 * 🤖 게임 화면 판단 (GAME_PLAN 5번).
 *
 * 집 PC 가 «화면이 바뀐 순간» 의 작은 사진(가로 768px)을 보내면, 기존 AI 엔진(`runAI`)이
 * 보고 장면·퀘스트·남길지·다음 행동을 JSON 한 가지 모양으로 답한다. 사진은 임시 폴더에 두고
 * **판단이 끝나면 바로 지운다**(서버에 남기지 않는다).
 *
 * 안전 규칙은 AI 답을 믿지 않고 **여기서 다시 거른다**:
 *   - 모양이 틀리면 → 대기
 *   - 기록 모드 → 행동은 대기(또는 정지)뿐. 버튼 0건
 *   - 감독 모드 → 프로필 버튼 목록에 있는 것만. 없는 버튼 이름이면 대기
 *   - 금지화면 단어가 보이면 → 무조건 정지
 *   - 경고·처음 보는 팝업·로그인 화면 → 정지 («확인 필요» / «로그인 필요»)
 */
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { runAI } from "../ai/run.js";
import { parseJsonLoose } from "../claude/parseResponse.js";
import { 장면들, type 장면 } from "./미션.js";
import { 상태행동, 금지버튼말, type 게임프로필 } from "./프로필.js";

export interface 판단결과 {
  장면: 장면;
  퀘스트: { 이름: string; 종류: "메인" | "서브" | "기타"; 단계: string } | null;
  남김: boolean;
  설명: string;
  행동: string;
  이유: string;
  /** 화면에 보인 눈에 띄는 글자 (금지화면 검사용) */
  보이는글: string;
  /** 안전 규칙이 AI 답을 바꿨으면 그 까닭 */
  막음?: string;
  /** 집 PC 가 멈춰야 할 때 화면에 띄울 상태 */
  멈춤상태?: "확인필요" | "로그인필요" | "금지화면";
}

export interface 판단상황 {
  퀘스트?: string | null;
  최근이벤트?: string[];
  /** 체크리스트에서 아직 빈 장면 — 감독 모드가 노릴 것 */
  빠진장면?: string[];
  /** 🧪 가상 게임 시험 때만 집 PC 가 보낸다. 진짜 게임에서는 비어 있다 */
  가상힌트?: Record<string, unknown> | null;
}

export const 대기답: 판단결과 = {
  장면: "기타", 퀘스트: null, 남김: false, 설명: "", 행동: "대기", 이유: "판단 답의 모양이 맞지 않아 기다립니다.", 보이는글: "",
};

export function 판단지시문(프로필: 게임프로필, 사진파일: string, 상황: 판단상황): string {
  const 버튼들 = 프로필.모드 === "감독" ? Object.keys(프로필.버튼) : [];
  const 행동들 = [...상태행동, ...버튼들];
  return `
[게임 화면 판단]
게임: ${프로필.이름} (${프로필.모드} 모드)
아래 사진 파일 하나를 Read 도구로 열어 보고, 지금 게임 화면이 어떤 장면인지 판단하라.
사진: ${사진파일}

지금 진행 중인 퀘스트: ${상황.퀘스트 || "(모름)"}
최근 이벤트(최신이 위):
${(상황.최근이벤트 ?? []).slice(0, 5).map((e) => `- ${e}`).join("\n") || "- (없음)"}
${상황.빠진장면?.length ? `아직 못 찍은 장면: ${상황.빠진장면.join(", ")}\n` : ""}${상황.가상힌트 ? `가상 게임 장면 힌트(시험용): ${JSON.stringify(상황.가상힌트)}\n` : ""}
규칙:
- 장면은 이 중 하나: ${장면들.join("|")}
- 퀘스트 이름·종류는 화면의 퀘스트 표시에서 읽은 그대로. 안 보이면 null.
- 남김: 공략 글에 쓸 만한 장면이면 true (퀘스트 받음·완료·보상·지도·도착·대화·보스·포획 등). 로딩·같은 이동 화면은 false.
- 설명: 사진 대체텍스트로 쓸 한 줄(30자 안팎). 화면에 없는 수치는 쓰지 마라.
- 행동은 이 중 하나만: ${행동들.join("|")}${프로필.모드 === "기록" ? "\n- 기록 모드다. 사람이 직접 플레이하므로 행동은 늘 «대기»." : ""}
- 보이는글: 화면에 크게 보이는 메뉴·창 제목 글자를 쉼표로 (예: 상점, 퀘스트, 지도).
- 결제·상점·거래소·경매장·채팅·우편·PvP 화면이면 행동은 «정지».
- 로그인·본인인증·OTP 화면이면 장면 «로그인», 행동 «정지».

최종 답변은 다른 설명 없이 순수 JSON 하나로만:
{"장면":"…","퀘스트":{"이름":"…","종류":"메인|서브|기타","단계":"…"},"남김":true,"설명":"…","행동":"…","이유":"한 줄","보이는글":"…"}
`.trim();
}

/** AI 답 → 판단결과. 모양이 틀리면 대기답. */
export function 판단읽기(원문: string): 판단결과 {
  const 값 = parseJsonLoose(원문) as Record<string, unknown> | null;
  if (!값 || typeof 값 !== "object") return { ...대기답 };
  const 장면 = String(값.장면 ?? "");
  if (!(장면들 as readonly string[]).includes(장면)) return { ...대기답, 이유: `모르는 장면 «${장면.slice(0, 20)}» — 기다립니다.` };
  const 행동 = String(값.행동 ?? "").trim();
  if (!행동) return { ...대기답 };
  let 퀘스트: 판단결과["퀘스트"] = null;
  const q = 값.퀘스트 as Record<string, unknown> | null | undefined;
  if (q && typeof q === "object" && String(q.이름 ?? "").trim()) {
    const 종류 = String(q.종류 ?? "");
    퀘스트 = {
      이름: String(q.이름).trim().slice(0, 60),
      종류: 종류 === "메인" || 종류 === "서브" ? 종류 : "기타",
      단계: String(q.단계 ?? "").slice(0, 60),
    };
  }
  return {
    장면: 장면 as 장면,
    퀘스트,
    남김: 값.남김 === true || 값.남김 === "true",
    설명: String(값.설명 ?? "").trim().slice(0, 80),
    행동,
    이유: String(값.이유 ?? "").trim().slice(0, 120),
    보이는글: String(값.보이는글 ?? "").slice(0, 200),
  };
}

/** AI 답을 안전 규칙으로 다시 거른다. **AI 가 무엇을 말하든 이 함수가 마지막 말이다.** */
export function 안전거르기(답: 판단결과, 프로필: 게임프로필): 판단결과 {
  const 결과 = { ...답 };
  const 화면글 = `${답.보이는글} ${답.설명} ${답.이유}`;
  const 걸린말 = 프로필.금지화면.find((말) => 말 && 화면글.includes(말));
  if (걸린말 || (프로필.모드 === "감독" && 금지버튼말.test(답.보이는글))) {
    return { ...결과, 행동: "정지", 남김: true, 막음: `금지 화면(${걸린말 ?? "상점·결제류"})이 보여 멈춥니다.`, 멈춤상태: "금지화면" };
  }
  if (답.장면 === "로그인") return { ...결과, 행동: "정지", 막음: "로그인 화면입니다. 공식 런처 자동 로그인을 확인해 주세요.", 멈춤상태: "로그인필요" };
  if (답.장면 === "경고" || 답.장면 === "팝업") {
    return { ...결과, 행동: "정지", 남김: true, 막음: `${답.장면} 화면이라 스스로 멈춥니다.`, 멈춤상태: "확인필요" };
  }
  if (프로필.모드 === "기록") {
    // 입력 0건. 정지는 입력이 아니라 «찍기를 멈춤» 이라 남겨 둔다.
    if (결과.행동 !== "대기" && 결과.행동 !== "정지") return { ...결과, 행동: "대기", 막음: "기록 모드라 행동은 하지 않습니다." };
    return 결과;
  }
  const 허용 = new Set<string>([...상태행동, ...Object.keys(프로필.버튼)]);
  if (!허용.has(결과.행동) || 금지버튼말.test(결과.행동)) {
    return { ...결과, 행동: "대기", 막음: `«${결과.행동.slice(0, 20)}» 은(는) 프로필 버튼 목록에 없어 누르지 않습니다.` };
  }
  return 결과;
}

/** 사진 한 장을 판단한다. 사진은 끝나면 지운다. AI 가 탈나면 대기. */
export async function 판단하기(프로필: 게임프로필, 사진: Buffer, 상황: 판단상황, timeoutMs = 60_000): Promise<판단결과> {
  const 폴더 = fs.mkdtempSync(path.join(os.tmpdir(), "game-judge-"));
  const 파일 = path.join(폴더, "screen.webp");
  try {
    fs.writeFileSync(파일, 사진);
    const 원문 = await runAI({ prompt: 판단지시문(프로필, 파일, 상황), readDir: 폴더, timeoutMs });
    return 안전거르기(판단읽기(원문), 프로필);
  } catch (탈) {
    return { ...대기답, 이유: `판단을 못 했습니다 — ${(탈 as Error).message.slice(0, 100)}` };
  } finally {
    fs.rmSync(폴더, { recursive: true, force: true });
  }
}
