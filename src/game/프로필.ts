/**
 * 사람이 고친 프로필을 저장하기 전에 다듬는다.
 *  - 기록 모드면 버튼을 비운다(입력 0건 — GAME_PLAN 1-6)
 *  - 금지 이름을 가진 버튼은 버린다
 *  - 숫자 칸은 범위 안으로
 */
export function 프로필다듬기(값: Partial<게임프로필>, 원래: 게임프로필): 게임프로필 {
  const 모드 = 값.모드 === "감독" ? "감독" : 값.모드 === "기록" ? "기록" : 원래.모드;
  const 버튼들: Record<string, 버튼> = {};
  if (모드 === "감독") {
    for (const [이름, b] of Object.entries(값.버튼 ?? 원래.버튼)) {
      if (금지버튼말.test(이름) || !b || typeof b !== "object") continue;
      const 좌표 = (n: unknown) => Math.max(0, Math.min(1, Number(n)));
      if (b.키) 버튼들[이름] = { 키: String(b.키).slice(0, 12) };
      else if (b.x !== undefined && b.y !== undefined) 버튼들[이름] = { x: 좌표(b.x), y: 좌표(b.y) };
    }
  }
  const 실행 = { ...(원래.실행 ?? { 파일: "" }), ...(값.실행 ?? {}) };
  if (모드 === "기록") 실행.런처시작버튼 = {};
  return {
    ...원래,
    ...값,
    id: 원래.id,
    이름: String(값.이름 ?? 원래.이름).slice(0, 30),
    모드,
    창제목: String(값.창제목 ?? 원래.창제목).slice(0, 60),
    하루상한분: Math.max(10, Math.min(720, Number(값.하루상한분 ?? 원래.하루상한분) || 240)),
    막힘판단분: Math.max(1, Math.min(60, Number(값.막힘판단분 ?? 원래.막힘판단분) || 5)),
    버튼: 버튼들,
    금지화면: (Array.isArray(값.금지화면) ? 값.금지화면 : 원래.금지화면).map((s) => String(s).trim()).filter(Boolean).slice(0, 30),
    영역: 값.영역 ?? 원래.영역,
    실행,
    기본참고주소: (Array.isArray(값.기본참고주소) ? 값.기본참고주소 : 원래.기본참고주소 ?? [])
      .map((s) => String(s).trim()).filter((s) => /^https?:\/\//.test(s)).slice(0, 5),
  };
}
