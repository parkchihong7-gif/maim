export interface 비율 { x: number; y: number; w?: number; h?: number }
export interface 버튼 { 키?: string; x?: number; y?: number }

export interface 게임프로필 {
  id: string;
  이름: string;
  모드: "감독" | "기록";
  창제목: string;
  해상도기준?: [number, number];
  하루상한분: number;
  실행?: { 파일: string; 인자?: string; 런처창제목?: string; 런처시작버튼?: 버튼; 창대기초?: number };
  버튼: Record<string, 버튼>;
  금지화면: string[];
  영역: Record<string, 비율>;
  막힘판단분: number;
  기본참고주소?: string[];
}

