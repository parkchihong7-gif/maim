/**
 * **제목을 「문장」이 아니라 「세부 키워드 조합」으로 잡는다.**
 *
 * 지금까지 나오던 제목은 기사 헤드라인에 가까웠다.
 *
 *   - "노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다"
 *   - "스크래치 4.0의 AI 도입 선언이 전 세계 게임 개발 꿈나무들을 충격에 빠뜨린 내막"
 *
 * 읽히기는 하는데, 이런 제목은 **아무도 검색창에 치지 않는 말**이다. 네이버에서
 * 글이 걸리려면 제목이 검색어를 닮아야 한다.
 *
 *   - "노원구 소형 아파트 대출 조건"
 *   - "초등 스크래치 게임 만들기"
 *
 * 또 하나. 네이버 C-Rank 는 글 한 편이 아니라 **블로그 전체가 어떤 주제에
 * 꾸준한가**를 본다. 그래서 제목 키워드가 카테고리 주제 안에 머물러야 하고,
 * 그 키워드가 본문에도 실제로 들어 있어야 한다. 아래 안내문이 그것을 시킨다.
 *
 * 프롬프트로 시키는 것만으로는 100% 지켜지지 않으므로, 받아 온 뒤에 한 번 더
 * 자로 재고(`제목재보기`), 본 제목이 규칙을 벗어났으면 이미 받아 둔 후보 제목
 * 중 규칙에 맞는 것으로 바꿔 끼운다(`제목고르기`). AI 를 다시 부르지 않는다 —
 * 한 번 더 부르면 3분이 더 들기 때문이다.
 */

/*
 * **3차 — 키워드 조합 + 후킹 문구, 최대 길이까지.**
 *
 * 2차에서 제목을 3~4낱말 키워드 조합으로 좁혔더니 이번엔 **너무 짧았다.**
 * "노원구 소형 아파트 대출 조건" 은 검색에는 걸리지만, 검색 결과 목록에서
 * 눌러 볼 까닭이 없다. 그래서 키워드 조합은 **맨 앞에 그대로** 두고, 그 뒤에
 * 누르고 싶게 만드는 **후킹 문구**를 붙여 네이버 검색 결과에 다 보이는
 * 길이(40자 안팎)까지 채운다.
 *
 *   "노원구 소형 아파트 대출 조건"                          ← 2차 (18자)
 *   "노원구 소형 아파트 대출 조건 2026 바뀐 한도 3가지 총정리"   ← 3차 (33자)
 *
 * 앞 키워드는 검색에 걸리게 하고(세부 키워드·C-Rank), 뒤 후킹은 눌러 보게 한다.
 * 기사 헤드라인 꼴(«~했더니 동네가 끓어올랐습니다», «~의 내막») 은 계속 막는다.
 */

/** 앞머리 키워드 조합의 낱말 수. 프롬프트로는 3~4개를 시킨다. */
export const 키워드낱말최소 = 2;
export const 키워드낱말최대 = 6;

/** 프롬프트로 시키는 길이 (공백 포함). 네이버 PC 검색 결과에 다 보이는 길이. */
export const 목표최소 = 32;
export const 목표최대 = 40;
/**
 * 자로 잴 때는 조금 봐 준다. AI 가 30자·42자를 내놓았다고 멀쩡한 제목을
 * 밀어내면 그게 더 손해다. 이 자가 막아야 할 것은 **키워드만 달랑 있는
 * 짧은 제목**과 **문장으로 흘러간 긴 제목**이다.
 */
export const 글자최소 = 24;
export const 글자최대 = 45;
/** 전체 낱말 수. 이보다 많으면 제목이 아니라 문장이다. */
export const 낱말최대 = 12;

/** 서술문으로 끝나는 꼴. 후킹 문구라도 «~습니다» 로 끝나면 기사·일기다. 물음표로 끝나는 물음은 봐 준다. */
const 종결어미 =
  /(습니다|합니다|됩니다|입니다|랍니다|십니다|했다|한다|된다|였다|졌다|이다|네요|어요|아요|에요|예요|해요|더라|더군요|거든요|잖아요|죠)$/;

/** 제목에 들어가면 곤란한 기호. 따옴표·꺾쇠는 검색 결과에서 지저분해 보인다. */
const 못쓰는기호 = /["'“”‘’「」『』<>;~]/;

/** 헤드라인 냄새가 나는 낚시 꼬리말. 후킹은 좋지만 이건 기사 제목이다. */
const 기사꼬리 = /(내막|전말|충격|경악|발칵|반전|화제|논란|근황)[!?.]*$/;

/**
 * 검색창에 안 치는 넓은 수식어. 이걸로 **시작**하면 앞머리 키워드 한 자리를 버린다.
 * (뒤쪽 후킹 문구에서는 써도 된다.)
 */
const 넓은머리말 = /^(요즘|최근|진짜|드디어|바로|화제의|충격의|역대급|레전드|소름|완전)\s/;

export type 제목판정 = { 괜찮나: boolean; 왜: string };

/**
 * 제목 한 줄이 「키워드 조합 + 후킹 문구」 꼴인지 자로 재 본다.
 *
 * @param 키워드 AI 가 따로 알려 준 앞머리 키워드 조합. 있으면 제목이 **그걸로
 *   시작하는지**까지 본다 — 검색에 걸리는 것은 앞머리다.
 */
export function 제목재보기(제목: string, 키워드 = ""): 제목판정 {
  const 글 = 제목.trim().replace(/\s+/g, " ");
  if (글.length < 글자최소) {
    return { 괜찮나: false, 왜: `${글자최소}자보다 짧다(${글.length}자) — 키워드만 있고 후킹 문구가 없다` };
  }
  if (글.length > 글자최대) return { 괜찮나: false, 왜: `${글자최대}자를 넘겼다(${글.length}자)` };

  const 낱말 = 글.split(" ");
  if (낱말.length > 낱말최대) return { 괜찮나: false, 왜: `낱말이 ${낱말.length}개로 문장에 가깝다` };

  if (못쓰는기호.test(글)) return { 괜찮나: false, 왜: "따옴표·꺾쇠 같은 기호가 들어 있다" };
  if (!글.endsWith("?") && 종결어미.test(글.replace(/[!.]+$/, ""))) {
    return { 괜찮나: false, 왜: "서술문처럼 끝난다" };
  }
  if (기사꼬리.test(글)) return { 괜찮나: false, 왜: "기사 헤드라인 꼬리말로 끝난다" };
  if (넓은머리말.test(글)) return { 괜찮나: false, 왜: "검색창에 안 치는 넓은 수식어로 시작한다" };
  if ((글.match(/[!?]/g) ?? []).length > 1) return { 괜찮나: false, 왜: "느낌표·물음표가 여러 개다" };

  const 앞 = 키워드.trim().replace(/\s+/g, " ");
  if (앞) {
    const 앞낱말 = 앞.split(" ").length;
    if (앞낱말 < 키워드낱말최소 || 앞낱말 > 키워드낱말최대) {
      return { 괜찮나: false, 왜: `앞머리 키워드가 ${앞낱말}낱말이다` };
    }
    if (!글.startsWith(앞)) return { 괜찮나: false, 왜: `제목이 키워드 조합 «${앞}» 으로 시작하지 않는다` };
  }
  return { 괜찮나: true, 왜: "" };
}

export function 제목꼴인가(제목: string, 키워드 = ""): boolean {
  return 제목재보기(제목, 키워드).괜찮나;
}

export type 제목고름 = {
  title: string;
  title_variants: string[];
  바꿨나: boolean;
  왜: string;
};

/**
 * 본 제목이 규칙을 벗어났으면, 후보 제목 중 규칙에 맞는 첫 번째 것으로 바꿔 끼운다.
 * 밀려난 본 제목은 버리지 않고 후보 맨 뒤에 넣어 둔다 — 사람이 보고 되돌릴 수 있게.
 * 쓸 만한 후보가 하나도 없으면 아무것도 바꾸지 않는다(나쁜 제목 < 없는 제목).
 */
export function 제목고르기(제목: string, 후보들: string[] = [], 키워드 = ""): 제목고름 {
  const 본것 = 제목.trim();
  const 후보 = 후보들.map((t) => t.trim()).filter(Boolean);

  // 본 제목만 «키워드로 시작하나» 를 본다. 후보는 공략 각도가 달라 앞머리 키워드도 다르다.
  const 잰것 = 제목재보기(본것, 키워드);
  if (잰것.괜찮나) return { title: 본것, title_variants: 후보, 바꿨나: false, 왜: "" };

  const 자리 = 후보.findIndex((t) => 제목꼴인가(t));
  if (자리 < 0) {
    return { title: 본것, title_variants: 후보, 바꿨나: false, 왜: `${잰것.왜} — 쓸 만한 후보 제목이 없어 그대로 둔다` };
  }

  const 뽑은것 = 후보[자리];
  const 남은것 = [...후보.slice(0, 자리), ...후보.slice(자리 + 1), 본것];
  return { title: 뽑은것, title_variants: 남은것, 바꿨나: true, 왜: 잰것.왜 };
}

/** 프롬프트에 그대로 들어가는 제목 규칙 안내문. 글 생성·미리보기 양쪽이 같이 쓴다. */
export function buildTitleRuleBlock(): string {
  return `
[제목 규칙 — 이번 글에서 가장 중요한 항목이다]
   제목은 **두 부분**으로 만든다: [앞머리 세부 키워드 조합] + [후킹 문구]
   - 앞머리: 독자가 **검색창에 그대로 쳐 볼 법한 세부 키워드 조합**, 띄어쓰기 기준 낱말 3~4개.
     조합 순서는 [지역·대상·상황] + [핵심 소재] + [알고 싶은 것(조건·방법·후기·비교·가격·순위)].
     이 앞머리를 keyword 칸에도 **똑같이** 적고, title 은 반드시 이 앞머리로 **시작**해야 한다.
   - 뒤쪽 후킹 문구: 검색 결과 목록에서 **눌러 보고 싶게** 만드는 말. 글 내용에 실제로 있는 것만 쓴다.
     아래 8가지 멈추는 이유 중 이 글에 맞는 것 하나를 골라 쓴다.
       돈(얼마 아끼나·얼마 드나) · 시간(5분이면·하루 만에) · 관계 · 지위 · 안전(사기·실수 피하기)
       · 호기심(몰랐던 1가지) · 비교(A vs B·순위) · 손실회피(놓치면 손해·이것부터 확인)
     숫자(2026, 3가지, 5분, 30%)를 하나 넣으면 훨씬 잘 눌린다.
   - **전체 길이는 공백 포함 ${목표최소}~${목표최대}자.** 네이버 검색 결과에 잘리지 않고 다 보이는
     최대 길이까지 채워라. 다 쓰고 나서 글자 수를 직접 세어 확인하라. 짧으면 후킹 문구를 늘려라.
   - 좋은 예:
     "노원구 소형 아파트 대출 조건 2026 바뀐 한도 3가지 총정리"
     "초등 스크래치 게임 만들기 주말 1시간이면 첫 작품 완성하는 법"
     "강남 원룸 전세 사기 예방 계약 전 이것 5가지만 확인하세요"
     "캠핑 화로대 추천 순위 3년 써 보고 고른 가성비 TOP5"
   - 나쁜 예(절대 이렇게 쓰지 마라):
     "노원구 소형 아파트 대출 조건"  ← 키워드만 있고 후킹이 없어 너무 짧다
     "노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다"  ← 기사 문장
     "스크래치 4.0의 AI 도입 선언이 전 세계 게임 개발 꿈나무들을 충격에 빠뜨린 내막"  ← 헤드라인 꼬리
   - '~습니다', '~했다', '~네요' 같은 서술형으로 끝내지 마라. 물음표로 끝나는 물음은 된다
     (예: "... 몰라서 손해 보셨나요?"). 느낌표·물음표는 하나까지만.
   - '내막', '전말', '충격', '경악', '반전', '논란' 같은 낚시 꼬리말을 쓰지 마라.
   - 따옴표·꺾쇠(「」<>)를 넣지 마라. 쉼표는 한 번까지 괜찮다.
   - '요즘', '최근', '진짜', '역대급' 같은 넓은 수식어로 **시작**하지 마라. 앞머리는 검색어 자리다.
   - 후킹 문구에 글에 없는 약속을 쓰지 마라. «무조건», «100%», «수익 보장» 은 금지다.
   - **검색창 시험** — 앞머리 키워드만 떼어 네이버 검색창에 친다고 상상해 보라. 누군가 실제로
     칠 법한 말이 아니면 앞머리부터 다시 써라.

[왜 이렇게 쓰나 — 세부 키워드 공략과 C-Rank, 그리고 클릭]
   - 넓은 키워드 한 개로는 상위에 못 올라간다. 낱말 3~4개로 좁힌 세부 키워드라야
     경쟁이 얕아서 검색 유입이 잡힌다. 그 키워드가 **제목 맨 앞**에 있어야 가장 세게 걸린다.
   - 걸려도 눌리지 않으면 소용없다. 뒤쪽 후킹 문구가 검색 결과 목록에서 눌리게 만든다.
   - 네이버 C-Rank 는 **블로그 전체가 한 주제에 얼마나 꾸준한가**를 본다. 앞머리 키워드는
     반드시 이 카테고리 주제 안에 머물러야 한다.
   - 앞머리 키워드를 **본문 첫 문단 안에 한 번**, 본문 전체에 걸쳐 3~5회 자연스럽게 다시 써라.
`.trim();
}
