/**
 * **제목을 「문장」이 아니라 「세부 키워드 조합」으로 잡는다.**
 *
 * 지금까지 나오던 제목은 기사 헤드라인에 가까웠다.
 *
 *   - "노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다"
 *   - "스크래치 4.0의 AI 도입 선언이 전 세계 게임 개발 꿈나무들을 충격에 빠뜨린 내막"
 *
 * 읽히기는 하는데, 이런 제목은 **아무도 검색창에 치지 않는 말**이다. 네이버에서
 * 글이 걸리려면 제목이 검색어를 닮아야 한다.
 *
 *   - "노원구 소형 아파트 대출 조건"
 *   - "초등 스크래치 게임 만들기"
 *
 * 또 하나. 네이버 C-Rank 는 글 한 편이 아니라 **블로그 전체가 어떤 주제에
 * 꾸준한가**를 본다. 그래서 제목 키워드가 카테고리 주제 안에 머물러야 하고,
 * 그 키워드가 본문에도 실제로 들어 있어야 한다. 아래 안내문이 그것을 시킨다.
 *
 * 프롬프트로 시키는 것만으로는 100% 지켜지지 않으므로, 받아 온 뒤에 한 번 더
 * 자로 재고(`제목재보기`), 본 제목이 규칙을 벗어났으면 이미 받아 둔 후보 제목
 * 중 규칙에 맞는 것으로 바꿔 끼운다(`제목고르기`). AI 를 다시 부르지 않는다 —
 * 한 번 더 부르면 3분이 더 들기 때문이다.
 */

/** 띄어쓰기 낱말 수. 프롬프트로는 3~4개를 시킨다. */
export const 낱말최소 = 3;
/**
 * 자는 6개까지 봐 준다. 지시하신 예시 "노원구 소형 아파트 대출 조건" 자체가
 * 5낱말이고, 실제로 받아 보면 5~6낱말이 흔하다. 이 자가 막아야 할 것은
 * **문장으로 흘러간 제목**이지 낱말 하나가 더 붙은 키워드 조합이 아니다.
 * 멀쩡한 키워드 제목을 낱말 수 하나 때문에 밀어내면 그게 더 손해다.
 * 문장인지 아닌지는 길이(30자)와 종결어미가 훨씬 정확하게 잡아낸다.
 */
export const 낱말최대 = 6;
/** 3~4낱말이면 보통 20자 안쪽이다. 30자를 넘으면 문장으로 흘렀다는 뜻. */
export const 글자최대 = 30;
/** 너무 짧으면 검색어로서 너무 넓다. */
export const 글자최소 = 6;

/** 문장으로 끝나는 꼴. 이게 붙으면 검색어가 아니라 서술문이다. */
const 종결어미 =
  /(습니다|합니다|됩니다|입니다|랍니다|십니다|했다|한다|된다|였다|졌다|이다|네요|어요|아요|에요|예요|해요|더라|더군요|거든요|잖아요|나요|까요|는가|은가|았나|었나|죠)$/;

/** 제목에 들어가면 곤란한 기호. 검색어에는 안 쓰는 것들이다. */
const 못쓰는기호 = /[,?!…~"'“”‘’「」『』\[\]<>·:;]/;

/** 헤드라인 냄새가 나는 꼬리말. 이게 붙으면 키워드가 아니라 기사 제목이다. */
const 기사꼬리 = /(내막|전말|이유|까닭|충격|경악|발칵|반전|화제|논란)$/;

/**
 * 검색창에 안 치는 넓은 수식어. 이걸로 시작하면 낱말 하나를 버리는 셈이다.
 * 실제 유입 검색어를 370건 훑어봐도 이런 말로 시작하는 것이 하나도 없었다.
 * '오늘'·'이번' 은 뺐다 — "오늘 금값 시세" 처럼 실제로 치는 말이기 때문이다.
 */
const 넓은머리말 = /^(요즘|최근|진짜|드디어|바로|화제의|충격의|역대급|레전드|소름|완전)\s/;

export type 제목판정 = { 괜찮나: boolean; 왜: string };

/** 제목 한 줄이 「세부 키워드 조합」 꼴인지 자로 재 본다. */
export function 제목재보기(제목: string): 제목판정 {
  const 글 = 제목.trim();
  if (글.length < 글자최소) return { 괜찮나: false, 왜: `${글자최소}자보다 짧다` };
  if (글.length > 글자최대) return { 괜찮나: false, 왜: `${글자최대}자를 넘겼다(${글.length}자)` };

  const 낱말 = 글.split(/\s+/).filter(Boolean);
  if (낱말.length < 낱말최소) return { 괜찮나: false, 왜: `낱말이 ${낱말.length}개뿐이다` };
  if (낱말.length > 낱말최대) return { 괜찮나: false, 왜: `낱말이 ${낱말.length}개로 너무 많다` };

  if (못쓰는기호.test(글)) return { 괜찮나: false, 왜: "쉼표·물음표 같은 기호가 들어 있다" };
  if (종결어미.test(글)) return { 괜찮나: false, 왜: "문장처럼 끝난다" };
  if (기사꼬리.test(글)) return { 괜찮나: false, 왜: "기사 헤드라인 꼬리말로 끝난다" };
  if (넓은머리말.test(글)) return { 괜찮나: false, 왜: "검색창에 안 치는 넓은 수식어로 시작한다" };

  return { 괜찮나: true, 왜: "" };
}

export function 제목꼴인가(제목: string): boolean {
  return 제목재보기(제목).괜찮나;
}

export type 제목고름 = {
  title: string;
  title_variants: string[];
  바꿨나: boolean;
  왜: string;
};

/**
 * 본 제목이 규칙을 벗어났으면, 후보 제목 중 규칙에 맞는 첫 번째 것으로 바꿔 끼운다.
 * 밀려난 본 제목은 버리지 않고 후보 맨 뒤에 넣어 둔다 — 사람이 보고 되돌릴 수 있게.
 * 쓸 만한 후보가 하나도 없으면 아무것도 바꾸지 않는다(나쁜 제목 < 없는 제목).
 */
export function 제목고르기(제목: string, 후보들: string[] = []): 제목고름 {
  const 본것 = 제목.trim();
  const 후보 = 후보들.map((t) => t.trim()).filter(Boolean);

  const 잰것 = 제목재보기(본것);
  if (잰것.괜찮나) return { title: 본것, title_variants: 후보, 바꿨나: false, 왜: "" };

  const 자리 = 후보.findIndex((t) => 제목꼴인가(t));
  if (자리 < 0) {
    return { title: 본것, title_variants: 후보, 바꿨나: false, 왜: `${잰것.왜} — 쓸 만한 후보 제목이 없어 그대로 둔다` };
  }

  const 뽑은것 = 후보[자리];
  const 남은것 = [...후보.slice(0, 자리), ...후보.slice(자리 + 1), 본것];
  return { title: 뽑은것, title_variants: 남은것, 바꿨나: true, 왜: 잰것.왜 };
}

/** 프롬프트에 그대로 들어가는 제목 규칙 안내문. 글 생성·미리보기 양쪽이 같이 쓴다. */
export function buildTitleRuleBlock(): string {
  return `
[제목 규칙 — 이번 글에서 가장 중요한 항목이다]
   - title 은 문장이 아니라, 독자가 **검색창에 그대로 쳐 볼 법한 세부 키워드 조합**이어야 한다.
   - **띄어쓰기 기준 낱말 3~4개**로 만든다. 내보내기 전에 띄어쓰기를 직접 세어 확인하라.
     아무리 많아도 5개를 넘기면 안 되고, 전체 길이는 ${글자최대}자 안쪽이어야 한다.
   - 조합 순서는 [지역·대상·상황] + [핵심 소재] + [독자가 알고 싶은 것] 으로 좁혀 간다.
     마지막 자리에는 조건·방법·후기·비교·가격·순위·정리 같은 말이 잘 어울린다.
   - 좋은 예: "노원구 소형 아파트 대출 조건", "초등 스크래치 게임 만들기"
   - 나쁜 예(절대 이렇게 쓰지 마라):
     "노원 13평 낡은 아파트가 7억 8000만원, 대출 조였더니 서민 동네가 끓어올랐습니다"
     "스크래치 4.0의 AI 도입 선언이 전 세계 게임 개발 꿈나무들을 충격에 빠뜨린 내막"
   - '~습니다', '~네요', '~했다' 같은 문장 종결형으로 끝내지 마라.
   - '~한 이유', '~내막', '~전말', '충격', '반전' 같은 기사 헤드라인 꼬리말을 쓰지 마라.
   - 쉼표·물음표·느낌표·따옴표·가운뎃점을 넣지 마라.
   - '요즘', '최근', '진짜', '드디어', '역대급' 같은 넓은 수식어로 시작하지 마라.
     검색창에 그런 말을 넣고 치는 사람은 없다. 낱말 한 자리를 버리는 것이다.
   - 연도·지역·대상 같은 한정어를 하나 붙이면 훨씬 잘 걸린다.
     (예: "2026 청년 전세자금대출 조건", "부산 초등 코딩학원 비용")
   - **검색창 시험** — 다 쓰고 나서, 이 제목을 그대로 네이버·구글 검색창에
     친다고 상상해 보라. 누군가 실제로 칠 법한 말이 아니면 처음부터 다시 써라.
     이 시험을 통과하지 못하는 제목은 아무리 잘 읽혀도 실패다.

[왜 이렇게 쓰나 — 세부 키워드 공략과 C-Rank]
   - 넓은 키워드 한 개로는 상위에 못 올라간다. 낱말을 3~4개로 좁힌 세부 키워드라야
     경쟁이 얕아서 검색 유입이 실제로 잡힌다.
   - 네이버 C-Rank 는 글 한 편이 아니라 **블로그 전체가 한 주제에 얼마나 꾸준한가**를 본다.
     그러니 제목 키워드는 반드시 이 카테고리 주제 안에 머물러야 한다. 주제를 벗어난
     자극적인 소재로 빠지면 글 하나는 터져도 블로그 지수는 깎인다.
   - title 에 쓴 핵심 키워드를 **본문 첫 문단 안에 한 번**, 그리고 본문 전체에 걸쳐
     3~5회 자연스럽게 다시 써라. 억지로 반복해서 문장이 어색해지면 안 된다.
`.trim();
}
