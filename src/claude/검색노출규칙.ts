/**
 * **본문을 「검색에 걸리는 꼴」로 쓰게 하는 규칙.**
 *
 * 실제로 운영 중인 네이버 블로그의 2026년 8월 통계를 보고 정했다. 짐작이 아니라
 * 그 블로그에 사람이 실제로 들어온 길을 세어서 나온 것들이다.
 *
 *   유입 경로    Google 50.4% · 네이버 이미지검색 24.6% · 네이버 통합검색 15.1%
 *               네이버 블로그검색 0.6%
 *   기기        PC 76.9% · 모바일 23.2%
 *   들어온 검색어 "경위서 양식", "근로계약서 양식", "협조문 양식쓰는법",
 *               "일당 근로계약서", "내용증명 양식", "지각 경위서 예시" …
 *
 * 여기서 읽히는 것이 넷이다.
 *
 *   ① 유입의 절반이 **구글**이다. 네이버만 보고 쓰면 절반을 버린다.
 *   ② 사람을 데려온 검색어는 거의 전부 **낱말 3~4개짜리 세부 키워드**였다.
 *      1차에서 제목을 키워드 조합으로 바꾼 판단이 이 숫자로 확인된 셈이다.
 *   ③ **네이버 이미지검색이 두 번째로 큰 유입원(24.6%)** 이다. 그림에 붙는
 *      설명글(alt)을 대충 쓰면 이 몫을 통째로 버린다.
 *   ④ 검색결과에 딸려 나오는 설명문은 본문 앞부분을 잘라서 만든다. 그러니
 *      첫 두세 문장이 사실상 광고 문구다.
 *
 * 아래 안내문이 이 넷을 본문 쓰는 규칙으로 옮긴 것이다.
 */
import type { PostDirective } from "../pipeline/directives.js";

export function buildSeoRuleBlock(directive: PostDirective): string {
  const 소제목둘 = Math.min(2, directive.sectionCount);
  return `
[검색 노출 규칙 — 네이버와 구글을 같이 노린다]
   이 글을 읽을 사람의 절반은 네이버가 아니라 구글에서 온다. 네이버 문법만
   따르지 말고, 아래를 둘 다 만족시켜라.

   1) 첫 두세 문장이 검색결과의 설명문이 된다
      - 네이버도 구글도 본문 앞부분을 잘라 검색결과 밑에 설명문으로 붙인다.
      - 그러니 첫 두세 문장 안에 (가) title 의 핵심 키워드를 그대로 한 번,
        (나) 이 글이 결국 무엇을 알려 주는 글인지를 반드시 담아라.
      - 인사말로 시작하더라도 그 인사 문장 안에 소재를 같이 넣어라.
        "안녕하세요" 만으로 세 문장을 채우면 설명문 자리를 통째로 버리는 것이다.

   2) 소제목에도 키워드를 심는다
      - 이모지로 시작하는 소제목 ${directive.sectionCount}개 중 최소 ${소제목둘}개에는
        title 키워드의 변형(같은 말·더 좁힌 말·이어지는 말)을 자연스럽게 넣어라.

   3) 묻고 답하는 구간을 한 군데 둔다
      - 독자가 검색창에 칠 법한 질문 한 줄을 소제목으로 세우고, 바로 아래
        두세 문장으로 **결론부터** 답하라.
      - 네이버 스마트블록과 구글 상단 요약이 이런 꼴을 골라서 올린다.

   4) 구체적인 수치·연도·지역·조건을 적는다
      - "많이 올랐어요" 가 아니라 "석 달 만에 8,000만 원 올랐어요".
      - 이런 구체어가 세부 키워드 검색과 맞물린다.
      - 다만 **지어내지 마라.** 확인되지 않은 숫자는 아예 쓰지 말고 범위나
        흐름으로 돌려 써라. 틀린 숫자 하나가 글 전체의 신뢰를 깎는다.

   5) 키워드를 억지로 반복하지 마라
      - 핵심 키워드는 본문 전체에서 3~5회면 충분하다. 그 이상 밀어 넣으면
        문장이 어색해지고 검색엔진도 이를 스팸으로 본다.

   6) 태그도 실제 검색어 꼴로 단다
      - 사람들이 실제로 치는 말은 [소재] + [양식·방법·조건·후기·가격·순위] 꼴이다.
      - 태그 10개 중 절반 이상을 이 꼴로 채워라. 한 낱말짜리 넓은 태그만
        늘어놓으면 아무 데도 걸리지 않는다.
`.trim();
}
