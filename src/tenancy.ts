/**
 * **누구의 자리인가.**
 *
 * 이 프로그램은 본래 한 사람이 쓰는 전제로 만들어졌다. 표에 "누구 것" 이라는
 * 칸이 없어서, 접속키를 두 사람에게 주면 서로의 카테고리와 초안이 다 보였다.
 * 지울 때도 마찬가지다 — 한 사람 몫만 골라 지울 방법이 없었다.
 *
 * 그래서 자리를 나눈다. 기준은 **1차키**다.
 *
 *   주인(관리자)  owner_key = ''   이 서버를 세운 사람. 원래 있던 글이 다 여기 있다
 *   체험           owner_key = 1차키  기간을 두고 맛보러 온 사람
 *
 * 왜 2차키가 아니라 1차키인가
 *   2차키는 기기마다 다르다(PC·노트북·휴대폰). 한 사람이 셋을 쓰는데 2차키로
 *   가르면 같은 사람의 글이 세 자리로 흩어진다. 사람은 1차키가 셈한다.
 *
 * 왜 매개변수로 넘기지 않고 여기에 두나
 *   글 한 편이 만들어지는 길이 깊다 — 라우트 → 생성 → 이미지 → 저장. 그 사이
 *   함수 전부에 "누구 것" 을 달고 다니면 한 군데만 빠져도 남의 자리에 쓴다.
 *   요청 하나를 통째로 감싸 두면 빠질 자리가 없다.
 */

import { AsyncLocalStorage } from "node:async_hooks";

export interface 쓰는이 {
  /** 1차키. **빈 값이면 주인의 자리다.** */
  ownerKey: string;
  /** admin(산 분·주인) / client(체험) */
  role: string;
}

/** 서버가 스스로 하는 일(매일 작업·정리)은 주인의 자리에서 돈다. */
export const 주인: 쓰는이 = { ownerKey: "", role: "admin" };

const 자리 = new AsyncLocalStorage<쓰는이>();

/** 이 안에서 벌어지는 모든 일은 `누구` 의 자리에서 일어난다. */
export function 자리에서<T>(누구: 쓰는이, 할일: () => T): T {
  return 자리.run(누구, 할일);
}

export function 지금(): 쓰는이 {
  return 자리.getStore() ?? 주인;
}

/** SQL 의 `owner_key = ?` 에 넣을 값. */
export function 지금주인(): string {
  return 지금().ownerKey;
}

/** 체험으로 들어온 사람인가. 주인이면 false. */
export function 체험인가(): boolean {
  return 지금().role !== "admin";
}

/** 체험 한 사람이 하루에 만들 수 있는 글의 수. */
export const 체험_하루상한 = 3;

/** 상한에 걸렸을 때 화면에 보일 말. */
export function 상한안내(만든수: number): string {
  return `체험 키는 하루 ${체험_하루상한}건까지 만들 수 있습니다. `
       + `오늘 ${만든수}건을 쓰셨습니다. 내일 다시 열립니다.\n\n`
       + `정식으로 쓰시면 건수 제한이 없고, 글과 설정이 **사장님 서버에** 쌓입니다.`;
}
