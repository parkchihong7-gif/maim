/**
 * **이 설정으로 아침에 얼마나 걸릴 것인가.**
 *
 * 예약을 깨우는 Cloud Scheduler 는 **30분까지만** 기다린다. 그 안에 못
 * 끝내면 서버는 계속 글을 쓰고 있는데 구글 쪽이 먼저 손을 놓고 「실패」로
 * 적는다. 화면에는 멀쩡해 보이는데 아침에 글이 모자라는, 알아차리기
 * 어려운 상태가 된다.
 *
 * 그래서 **설정을 바꾸실 때 그 자리에서 셈해 보인다.** 「글자수를 너무
 * 올리면 실패할 수 있습니다」 같은 고정된 경고문은 아무도 안 읽는다.
 * 지금 넣으신 값으로 «18분 / 30분» 이라고 보여 주면 읽힌다.
 *
 * 셈은 어림이다
 *   진짜 클로드로 재 보니 3,000자 한 편에 327초가 걸렸다. 그런데 같은
 *   길이라도 웹 검색이 길어지거나 분량이 모자라 다시 쓰면 훌쩍 넘는다.
 *   그래서 **넉넉히 잡는다** — 모자라게 잡아 「괜찮다」 고 해 놓고 아침에
 *   실패하는 쪽이 훨씬 나쁘다.
 */

/** Cloud Scheduler 가 기다려 주는 시간(초). 만들 때 1800s 로 건다. */
export const 기다려주는초 = 1800;

/** 글 한 편에 걸릴 시간(초)을 넉넉히 어림한다. */
export function 한편초(최소분량: number): number {
  // 바탕 3분 + 1,000자마다 1분. 3,000자면 6분.
  return 180 + Math.round((최소분량 / 1000) * 60);
}

export type 위험도 = "safe" | "tight" | "over";

export interface 시간어림 {
  perPostSec: number;
  totalSec: number;
  limitSec: number;
  level: 위험도;
  message: string;
}

export function 시간재보기(최소분량: number, 건수: number): 시간어림 {
  const 한편 = 한편초(최소분량);
  const 합 = 한편 * Math.max(0, 건수);
  const 분 = Math.round(합 / 60);
  const 한도분 = Math.round(기다려주는초 / 60);

  // 70% 를 넘으면 «아슬아슬» 이다. 80% 로 뒀다가 24분(=80%)이 「여유가
  // 있습니다」 로 나왔는데, 30분 한도에 24분이면 여유가 아니다. 재시도
  // 한 번이면 바로 넘는다.
  let level: 위험도 = "safe";
  if (합 > 기다려주는초) level = "over";
  else if (합 > 기다려주는초 * 0.7) level = "tight";

  const 머리 = `${최소분량}자 × ${건수}건이면 아침에 **약 ${분}분** 걸립니다 (한도 ${한도분}분).`;
  const 꼬리 =
    level === "over"
      ? " ⛔ **한도를 넘습니다.** 이대로 두시면 아침에 일부만 만들어지고 실패로 끝납니다. "
        + "글자수를 줄이시거나 건수를 줄여 주세요."
      : level === "tight"
        ? " ⚠️ **아슬아슬합니다.** 분량이 모자라 다시 쓰는 일이 겹치면 넘길 수 있습니다. "
          + "한 단계만 줄이시길 권합니다."
        : " 여유가 있습니다.";

  return { perPostSec: 한편, totalSec: 합, limitSec: 기다려주는초, level, message: 머리 + 꼬리 };
}
