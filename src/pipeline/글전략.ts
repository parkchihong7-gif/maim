/**
 * **글 전략 — 레인(🔥 이슈 · 📘 정보형 · 🧱 일반)과 그에 맞는 쓰기 규칙(F).**
 *
 * 사장님 실측(10-08): 출시 전날 쓴 «도깨비의 세계 직업·스킬 조합 3가지» 는 유입 2,810,
 * 비율로 고른 골드 키워드 글은 메인에 떠도 유입 22. 이슈 글은 **빨리, 답부터, 날짜를 밝혀** 써야 하고,
 * 경쟁 글이 몰리면 **후속 글로 이어 가야** 오래 버틴다.
 * 순수 함수다 — 네트워크·DB 없음.
 */
export type 레인 = "issue" | "info" | "general";
export const 레인이름: Record<레인, string> = { issue: "🔥 이슈", info: "📘 정보형", general: "🧱 일반" };

/** 글쓰기에 덧붙이는 주문. 비면 예전과 똑같이 쓴다. */
export interface 글주문 {
  /** 이번 글의 주제 키워드 — 보관함보다 먼저 */
  키워드?: string;
  /** 이번 글의 각도 (예: «쿠폰·초보 가이드») */
  각도?: string;
  레인?: 레인;
  /** 🎮 달력의 단계 글이면 */
  이벤트?: { id: number; step: string; title: string; date: string };
}

/** 레인을 정한다 — 주문이 먼저, 그다음 보관함 키워드의 급상승·의도, 그다음 카테고리 성격. */
export function 레인정하기(주문: 글주문 | undefined, 보관: { surge?: number | null; info?: boolean } | null, 뉴스형: boolean): 레인 {
  if (주문?.레인) return 주문.레인;
  if (주문?.이벤트) return "issue";
  if (보관?.surge) return "issue";
  if (보관?.info) return "info";
  if (뉴스형) return "issue";
  return "general";
}

/** 한국어 날짜 «2026년 10월 8일». */
export function 한국날짜(ymd: string): string {
  const [y, m, d] = ymd.split("-").map(Number);
  return y && m && d ? `${y}년 ${m}월 ${d}일` : ymd;
}

export function 전략블록(레인: 레인, 키워드: string, 오늘: string, 주문?: 글주문): string {
  const 줄: string[] = [];
  const 키 = 키워드 ? `«${키워드}»` : "주제 키워드";
  if (레인 === "issue") {
    줄.push(
      "[🔥 이슈 글 규칙 — 지금 뜨는 주제다. 급하게 찾는 사람에게 바로 답한다]",
      `- 제목 맨 앞에 ${키} 를 두고, 날짜·버전·숫자 중 하나를 넣어라 (예: «${키워드 || "OO"} ${한국날짜(오늘).replace(/^\d+년 /, "")} 정리 3가지»).`,
      "- 첫 문단 2~3문장 안에 독자가 찾는 답(일정·결론·추천)을 먼저 말하라. 배경 설명은 그 뒤에.",
      `- 본문 앞쪽에 «(${한국날짜(오늘)} 기준)» 한 줄을 넣어 언제 정보인지 밝혀라.`,
      "- 확인되지 않은 날짜·숫자·보상은 지어내지 마라. 모르면 «공식 발표 전» 이라고 적어라.",
      "- 소제목은 검색하는 사람이 실제로 묻는 질문 꼴로 써라 (예: «어떤 직업이 초보에게 좋을까?»).",
      "- 마지막 문단에 다음에 이어질 정보(쿠폰·공략·업데이트)를 정리해 두겠다는 예고 한 줄을 넣어라.",
    );
  } else if (레인 === "info") {
    줄.push(
      "[📘 정보형 글 규칙 — 답을 찾으러 온 사람이다]",
      `- 제목 앞머리에 ${키} 를 두고 숫자(3가지·5단계 등)를 넣어라.`,
      "- 첫 문단에 결론(답)을 먼저 말하고, 본문은 단계·목록·비교표로 정리하라.",
      "- 사이트 주소·다운로드 안내처럼 «다른 곳으로 보내는» 글이 되지 않게, 이 글 안에서 답이 끝나게 써라.",
    );
  }
  if (주문?.이벤트) {
    줄.push(`[🎮 일정] «${주문.이벤트.title}» — ${한국날짜(주문.이벤트.date)}. 오늘(${한국날짜(오늘)})과의 차이를 생각해 «출시 전/당일/출시 후» 시점에 맞게 써라.`);
  }
  if (주문?.각도) {
    줄.push(`[이번 글의 각도] ${주문.각도} — 이 각도 하나에 집중하라. 같은 주제의 다른 각도(이미 쓴 글)는 한두 줄로만 언급하라.`);
  }
  return 줄.join("\n");
}
